/// Current wall clock time in unix milliseconds.
///
/// Timestamps in the protocol are informational: they order history entries but
/// are never trusted for security decisions, because clocks drift and peers can
/// lie about them.
#[must_use]
pub fn now_millis() -> i64 {
    use std::time::{SystemTime, UNIX_EPOCH};

    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_or(0, |elapsed| elapsed.as_millis() as i64)
}
