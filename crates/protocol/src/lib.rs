//! # clipmesh-protocol
//!
//! The wire contract every ClipMesh node speaks: protobuf messages, the
//! length-delimited framing on top of TCP, and the validated clipboard payload
//! model.
//!
//! This crate is deliberately platform independent and dependency light. It
//! knows nothing about sockets, TLS, Tauri, Android or the operating system
//! clipboard - it only knows how to turn clipboard content into bytes and back
//! again, safely.
//!
//! ```no_run
//! use clipmesh_protocol::{DeviceId, Envelope, TextPayload};
//!
//! let payload = TextPayload::new_local("copied on device A", DeviceId::new());
//! let envelope = Envelope::text(payload.to_proto());
//! let frame = clipmesh_protocol::frame::encode(&envelope).unwrap();
//! assert_eq!(&frame[..4], &(frame.len() as u32 - 4).to_be_bytes());
//! ```

